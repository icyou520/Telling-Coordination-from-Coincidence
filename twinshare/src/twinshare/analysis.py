"""One analysis: the interaction share with its memory-gap prediction, trust checks, closure and influence, and a
verdict in plain language.

Trust checks (each pass / warn / fail, with what it means):
  data          enough rows and cross-fitting blocks for an interval to mean something
  virtual       members shifted in time against each other (each member kept intact, coordination destroyed):
                S should be about 0; if not, slow drifts or trends are being read as coordination
  null twins    the analyst's own fitted twins run as independent members (sharing only the recorded causes and
                same-day shocks): S should be about 0 at this sample size; the spread is the false-alarm band
  power         the same twins with a known spillover added (each member responds to yesterday's average shock):
                S should be detectably positive; if not, the data may be too short to see coordination this size
  memory gap    the measured S should agree with the memory gap; disagreement points to nonlinearity or changes
                over time, and to trusting the fitted share less
  stability     S in the first and second half of the period should not have opposite signs
"""

from __future__ import annotations

from dataclasses import dataclass, field, replace

import numpy as np

from . import engine as E
from .data import Panel


@dataclass
class Check:
    name: str
    status: str            # pass, warn, fail, info
    value: str
    meaning: str


@dataclass
class Result:
    panel: Panel
    design: E.Design
    seed: int
    S: float
    interval: tuple[float, float]
    memory_gap: dict
    virtual: list[float]
    gap_floor: float
    null: list[float]
    power: list[dict]
    periods: list[dict]
    halves: tuple[float, float]
    no_covariates: float | None
    closure: float | None
    influence: np.ndarray | None
    block: int = 0
    block_shares: dict[int, float] = field(default_factory=dict)
    checks: list[Check] = field(default_factory=list)
    verdict: str = ""
    explanation: str = ""
    errors: E.Errors | None = None


# ---------------------------------------------------------------- known-answer simulations from the fitted twins

def fit_twins(x, z, d):
    """Each member's twin fitted on all rows: weights on its history windows (W), on the causes (G), intercept (B),
    and residuals (rows, N)."""
    h, env, y = E.history(x, d), E.causes(z, d), x[d.lead:]
    ones = np.ones(len(y), bool)
    n, k = x.shape[1], len(d.windows)
    W, G, B, R = np.empty((n, k)), np.empty((n, env.shape[1])), np.empty(n), np.empty_like(y)
    for i in range(n):
        xi = np.column_stack([h[:, i], env])
        w, b = E.ridge_coef(xi, y[:, i], ones, d.lam)
        W[i], G[i], B[i] = w[:k], w[k:], b
        R[:, i] = y[:, i] - xi @ w - b
    return W, G, B, R


def simulate(x, z, d, twins, rng, kappa=0.0):
    """Members generated by their fitted twins, with residual rows resampled together (same-day shocks stay
    correlated, as in the data). kappa > 0 adds a spillover: each member also takes kappa times yesterday's average
    shock of all members. Returns None if the simulation diverges."""
    W, G, B, R = twins
    t_all, n = x.shape
    xs = np.empty_like(x)
    xs[: d.lead] = x[: d.lead]
    eps = R[rng.integers(0, len(R), t_all)]
    c = np.zeros((t_all + 1, n))
    c[1: d.lead + 1] = np.cumsum(xs[: d.lead], 0)
    drive = B + E.causes(z, d) @ G.T              # rows lead..T-1
    centre, scale = x.mean(0), 50 * x.std(0) + 1e-12
    for t in range(d.lead, t_all):
        s = t - d.horizon + 1
        feats = np.stack([(c[s] - c[s - w]) / w for w in d.windows], -1)
        v = drive[t - d.lead] + (feats * W).sum(1) + eps[t] + kappa * eps[t - 1].mean()
        if not np.all(np.abs(v - centre) < scale):
            return None
        xs[t] = v
        c[t + 1] = c[t] + v
    return xs


# ---------------------------------------------------------------- the analysis

def _periods(times, errors, lead, k=6):
    rows = len(errors.e_g)
    edges = np.linspace(0, rows, k + 1).astype(int)
    out = []
    for a, b in zip(edges[:-1], edges[1:]):
        m = np.zeros(rows, bool)
        m[a:b] = True
        out.append({"start": times[lead + a], "end": times[lead + b - 1], "S": errors.S_over(m)})
    return out


def analyze(panel: Panel, design: E.Design = E.Design(), seed: int = 0, n_virtual: int = 5, n_null: int = 8,
            n_power: int = 2, kappa: float = 0.5, detail: bool = True, progress=lambda msg: None) -> Result:
    x, z, d = panel.values, panel.covariates, design
    rng = np.random.default_rng(seed)
    rows = len(x) - d.lead
    if rows < 5 * d.folds * 2:
        raise ValueError(f"only {rows} usable rows after the longest window ({d.lead}); need far more")

    progress("interaction share")
    err = E.share(x, z, d)
    S, ci = err.S, err.interval(rng)
    progress("memory gap")
    gap = E.memory_gap(x, z, d)
    u = E.residualize(x, z)
    floor = float(np.median([E.s_pred(*E.memories(E.shift(u, rng), d.lead), d) for _ in range(n_virtual)]))
    progress("virtual groups")
    virtual = [E.share(E.shift(u, rng), z[:, :0], d).S for _ in range(n_virtual)]
    progress("simulated twins")
    twins = fit_twins(x, z, d)
    null = [s for s in (_sim_share(x, z, d, twins, rng, 0.0) for _ in range(n_null)) if s is not None]
    power = [p for p in (_sim_share(x, z, d, twins, rng, kappa, full=True) for _ in range(n_power)) if p is not None]
    half = np.arange(rows) < rows // 2
    halves = (err.S_over(half), err.S_over(~half))
    no_cov = E.share(x, z[:, :0], d).S if z.shape[1] else None
    b = d.block_size(rows)
    blocks = {n: E.share(x, z, replace(d, block=n)).S for n in (max(b // 2, d.lead + 1), 2 * b)}
    closure = infl = None
    if detail:
        progress("closure and influence")
        closure = E.gain(x, z, d)
        infl = E.influence(x, z, d)

    res = Result(panel, d, seed, S, ci, gap, virtual, floor, null, power, _periods(panel.times, err, d.lead),
                 halves, no_cov, closure, infl, block=b, block_shares=blocks, errors=err)
    res.checks = checks(res, rows, int(err.block.max()) + 1, n_null)
    res.verdict, res.explanation = verdict(res)
    return res


def _sim_share(x, z, d, twins, rng, kappa, full=False):
    xs = simulate(x, z, d, twins, rng, kappa)
    if xs is None:
        return None
    e = E.share(xs, z, d)
    if not full:
        return e.S
    lo, hi = e.interval(rng, 400)
    return {"S": e.S, "lo": lo, "hi": hi, "S_pred": E.memory_gap(xs, z, d)["S_pred"]}


def noise(r: Result) -> float:
    """Sampling spread of S under independence, from the null twins (floor 0.002)."""
    return max(float(np.std(r.null, ddof=1)) if len(r.null) > 2 else 0.01, 0.002)


def null_bar(r: Result) -> float:
    """S must exceed this to count as coordination: the null twins' mean plus three spreads."""
    return (float(np.mean(r.null)) if r.null else 0.0) + 3 * noise(r)


def checks(r: Result, rows: int, blocks: int, n_null: int) -> list[Check]:
    out = []
    ok = rows >= 300 and blocks >= 12
    out.append(Check("data", "pass" if ok else "warn", f"{rows} rows in {blocks} blocks, {r.panel.shape[1]} members",
                     "Enough history for the interval to be meaningful." if ok else
                     "Short series: intervals are rough and the trust checks below are noisy. Treat any result as a "
                     "screen, not a measurement."))

    sig = noise(r)
    vm = float(np.mean(r.virtual))
    st = ("pass" if vm <= max(0.01, 0.2 * abs(r.S), 3 * sig) else
          "warn" if vm <= max(0.02, 0.4 * abs(r.S), 5 * sig) else "fail")
    out.append(Check("virtual groups", st, f"mean S {vm:+.4f} (range {min(r.virtual):+.4f} to {max(r.virtual):+.4f}) "
                     f"over {len(r.virtual)} shifted groups",
                     {"pass": "Members shifted against each other show no coordination, as they should.",
                      "warn": "Shifted groups show a little apparent coordination: slow drifts may be inflating S.",
                      "fail": "Shifted groups, which cannot coordinate, show a share: trends or slow drifts are being "
                              "read as coordination. Detrend the members or record the drift as a cause."}[st]))

    if len(r.null) < n_null:
        out.append(Check("null twins", "warn", f"{n_null - len(r.null)} of {n_null} simulations diverged",
                         "The fitted twins are unstable when run forward; the false-alarm band is incomplete."))
    if r.null:
        bias = float(np.mean(r.null))
        st = ("pass" if -0.03 <= bias <= max(0.01, 0.2 * abs(r.S)) else
              "warn" if bias <= max(0.03, 0.5 * abs(r.S)) else "fail")
        low = bias < -0.03
        out.append(Check("null twins", st, f"mean {bias:+.4f}, spread {sig:.4f} over {len(r.null)} "
                         f"independent simulations; coordination needs S > {null_bar(r):+.4f}",
                         {"pass": "Independent members built from your own twins give S near 0 (slightly below 0 is "
                                  "the estimator erring on the safe side): no false alarm at this sample size. Their "
                                  "spread sets the bar S has to clear.",
                          "warn": "Independent members give S well below 0: the estimator is conservative here and "
                                  "small coordination may be missed." if low else
                                  "Independent members give a small positive S on average: read S against the bar.",
                          "fail": "Independent members already give a sizeable S: the measurement is biased at this "
                                  "sample size. Do not interpret S."}[st]))
    if r.power:
        det = sum(p["lo"] > 0 for p in r.power)
        st = "pass" if det == len(r.power) else "warn"
        out.append(Check("power", st, f"known spillover gives S {np.mean([p['S'] for p in r.power]):+.4f}; "
                         f"detected in {det}/{len(r.power)}",
                         "A modest spillover between members would be detected in data like yours." if st == "pass"
                         else "A modest spillover between members would not reliably be detected here: a null result"
                              " says little."))

    sp = r.memory_gap["S_pred"]
    diff = abs(r.S - sp)
    st = "pass" if diff <= 0.02 + 0.1 * abs(sp) + (r.interval[1] - r.interval[0]) else "warn"
    out.append(Check("memory gap", st, f"measured {r.S:+.4f}, predicted {sp:+.4f} (floor {r.gap_floor:+.4f})",
                     "The fitted share agrees with the fit-free memory-gap prediction." if st == "pass" else
                     "The fitted share and the memory gap disagree: nonlinear dynamics, rare events or changes over "
                     "time. Trust the direction more than the size."))

    a, b = r.halves
    flip = a * b < 0 and min(abs(a), abs(b)) > 0.01
    out.append(Check("stability", "warn" if flip else "pass", f"first half {a:+.4f}, second half {b:+.4f}",
                     "The two halves disagree in sign: the coordination is not a stable property of this period."
                     if flip else "The share has the same character in both halves of the period."))

    if r.block_shares:
        spread = max(abs(s - r.S) for s in r.block_shares.values())
        st = "pass" if spread <= max(0.01, 0.25 * abs(r.S), 2 * sig) else "warn"
        out.append(Check("block length", st, f"S {r.S:+.4f} with {r.block}-step blocks; "
                         + ", ".join(f"{s:+.4f} with {n}" for n, s in r.block_shares.items()),
                         "The share does not depend on how time is cut for cross-fitting." if st == "pass" else
                         "The share changes with the cross-fitting block length: the series drift (regimes, trends), "
                         "and longer test blocks sit further from the training levels. Read the shorter-block value, "
                         "and consider recording the drift as a cause."))

    if r.no_covariates is not None:
        out.append(Check("recorded causes", "info", f"without them S would be {r.no_covariates:+.4f}",
                         "A share computed without the recorded causes mixes coordination with the members' common "
                         "response to those conditions (it can come out higher or, when the causes dominate the "
                         "group's swings, lower). The value with the causes is the one to read."))
    if r.closure is not None:
        out.append(Check("closure", "info", f"member detail improves the group forecast by {r.closure:+.4f}",
                         "Near 0: the group's own history is enough to forecast it (closed). Positive: knowing "
                         "individual members' recent histories adds predictive information about the group."))
    return out


def verdict(r: Result) -> tuple[str, str]:
    lo, hi = r.interval
    status = {c.name: c.status for c in r.checks}
    broken = [n for n in ("virtual groups", "null twins") if status.get(n) == "fail"]
    above_null = r.S > null_bar(r)
    if broken:
        return ("Not interpretable", f"A trust check failed ({', '.join(broken)}), so S = {r.S:+.3f} cannot be read "
                "as coordination. See the checks for what to change.")
    if lo > 0 and above_null:
        size = "strong" if r.S >= 0.1 else "moderate" if r.S >= 0.03 else "small"
        return (f"Coordination detected ({size})",
                f"The group is forecast better by its own history than by adding up its members' own forecasts: "
                f"S = {r.S:+.3f} (90% interval {lo:+.3f} to {hi:+.3f}). About {100 * r.S:.1f}% of the group "
                "forecast's error under the twin is removed by coordination between members, or by a shared driver "
                "that is not among the recorded causes and that each member reveals poorly. Only an intervention "
                "or a recorded driver can tell those apart.")
    if lo > 0:
        return ("Inconclusive", f"S = {r.S:+.3f} is above 0 (90% interval {lo:+.3f} to {hi:+.3f}) but not clearly "
                f"above what independent members built from your own twins produce (bar {null_bar(r):+.3f}).")
    weak = "power" in status and status["power"] != "pass"
    return ("No coordination detected",
            f"S = {r.S:+.3f} (90% interval {lo:+.3f} to {hi:+.3f}): the members' own histories and the recorded "
            "causes forecast the group as well as its own history does."
            + (" The power check failed, so this is absence of evidence, not evidence of absence." if weak else ""))
