def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("experiments", nargs="*", help=f"any of: {', '.join(EXPERIMENTS)}")
    parser.add_argument("--quick", action="store_true", help="smaller, faster simulations")
    parser.add_argument("--out", type=Path, default=Path("results"))
    args = parser.parse_args()
    unknown = set(args.experiments) - set(EXPERIMENTS)
    if unknown:
        parser.error(f"unknown experiment(s): {', '.join(sorted(unknown))}")

    args.out.mkdir(parents=True, exist_ok=True)
    chosen = args.experiments or list(EXPERIMENTS)
    sections = []
    for key in chosen:
        title, fn = EXPERIMENTS[key]
        banner = f"\n{'=' * 78}\n {title}\n{'=' * 78}"
        print(banner)
        t0 = time.time()
        text = fn(args.out, args.quick)
        print(f"  ({time.time() - t0:.1f}s)")
        sections.append(banner + "\n" + text)

    (args.out / "summary.txt").write_text("\n".join(sections) + "\n")
    print(f"\nSummary written to {args.out / 'summary.txt'}")


if __name__ == "__main__":
    main()
